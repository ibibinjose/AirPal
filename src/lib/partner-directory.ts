/** Pure substring filter for the unclaimed directory (case-insensitive). */
export function filterUnclaimedPartners(names: readonly string[], query: string): string[] {
  const q = query.trim().toLowerCase();
  if (!q) return [...names];
  return names.filter((name) => name.toLowerCase().includes(q));
}
